from typing import Any, Protocol, runtime_checkable


@runtime_checkable
class UsuarioRepositoryInterface(Protocol):
    def get_by_id(self, user_id: int) -> Any: ...
    def get_by_email(self, email: str) -> Any: ...
    def create(self, email: str, password_hash: str) -> Any: ...


@runtime_checkable
class ReservaRepositoryInterface(Protocol):
    def get_by_id(self, reserva_id: int) -> Any: ...
    def buscar_solapamientos(
        self, cancha: str, fecha: str, hora_inicio: str, hora_fin: str
    ) -> list[Any]: ...
    def crear_reserva(
        self, cancha: str, fecha: str, hora_inicio: str, hora_fin: str, usuario_id: int
    ) -> Any: ...
    def listar_por_usuario(
        self, usuario_id: int, skip: int = 0, limit: int = 20
    ) -> list[Any]: ...
    def eliminar_reserva(self, reserva_id: int) -> bool: ...
